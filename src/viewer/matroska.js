/**
 * Matroska (`.mkv`) subtitle extraction, text tracks only.
 *
 * ## Why this is written rather than imported
 *
 * `PLAN-local-video.md` §11 chose `ebml-stream` + our own Matroska layer. **That
 * choice cannot be executed as written and is reversed here.** The project has no
 * bundler and no `dependencies` block, `src/` ships to the browser exactly as it
 * is written, so a bare `import 'ebml-stream'` cannot resolve. Taking it would
 * mean either a build step (changing how the project ships, for one feature) or
 * vendoring Node's stream implementation, which is what `ebml-stream` is built on
 * and is roughly as large as the parser itself.
 *
 * The reasoning for preferring a library was that EBML correctness is a bad place
 * to save a dependency, because a parser that passes three fixtures fails on the
 * fourth, on a user's film, where we cannot see it. **That concern is right, and
 * the mitigation is not a library: it is testing against real files.** The
 * fixtures for this module are generated by `ffmpeg` (`test/fixtures/`), not
 * written by hand, so they are files a real muxer produced.
 *
 * What makes the hand-rolled version safe enough:
 *   - The subset needed is small. We read `Tracks` for discovery and
 *     `Cluster` blocks for cues, and ignore everything else BY SIZE, so an
 *     element we do not understand costs nothing and cannot derail us.
 *   - Unknown and malformed input FAILS CLOSED. A codec we do not recognise is
 *     reported, never guessed at, so the failure is a message rather than a
 *     silently empty transcript.
 *   - The genuinely fiddly parts of EBML, unknown-size elements, `Void`, `CRC-32`
 *, are each a few lines and are covered by tests.
 *
 * ## What is deliberately not supported
 *
 * **Image subtitle codecs**, `S_HDMV/PGS` (Blu-ray), `S_VOBSUB` (DVD),
 * `S_DVBSUB`, `S_ARIBSUB`. These are pictures of text: there is no string in them
 * to mark, and extracting one is OCR, which is a different project. They are
 * detected and named so the caller can say so, rather than appearing as a track
 * that yields nothing.
 *
 * ## Structure
 *
 * The parser takes a `read(offset, length)` function rather than an array or a
 * stream. That is what lets it work on a multi-gigabyte film without loading it
 * into memory: elements are walked by their declared SIZE, large ones are skipped
 * by seeking forward, and only the regions we need are ever read.
 */

