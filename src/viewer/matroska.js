/**
 * How much to read at once.
 *
 * A single `Cluster` has to fit inside this for its cues to be read, because the
 * window is what we are willing to hold in memory at one time. A cluster is
 * normally well under a megabyte, it is a few seconds of media, so 8 MB is
 * generous while keeping the peak far below a whole film.
 */
const WINDOW_BYTES = 8 * 1024 * 1024;

/** An element larger than this is skipped without trying to read it. */
const MAX_ELEMENT_BYTES = WINDOW_BYTES;

/**
 * An EBML variable-length integer, which is how every id and size is stored.
 *
 * The first byte's leading zero count gives the total width: `0b1000_0002`-style
 * markers mean a 1-byte vint, `0b0100_0000` a 2-byte one, and so on. The value
 * bits across those bytes are the number, and the marker itself is discarded.
 *
 * Two details that are easy to get wrong and both matter:
 *   - A size of "all ones" (`0xFF` for a 1-byte vint, and so on) means UNKNOWN
 *     SIZE, not a gigantic element. A real `Segment` element uses it, so treating
 *     it as a number skips the entire file.
 *   - `keepMarker` is needed for ids but not for sizes, because an id is compared
 *     to a constant WITH its marker byte and a size is used as a number without.
 *
 * @param {Uint8Array} bytes
 * @param {number} offset
 * @param {boolean} [keepMarker] Include the length marker in the value (for ids).
 * @returns {{value: number, length: number, unknown: boolean}|null} null if the
 *   bytes do not hold a complete vint.
 */
export function readVint(bytes, offset = 0, keepMarker = false) {
  if (offset >= bytes.length) return null;
  const first = bytes[offset];
  if (first === 0) return null; // more than 8 bytes wide: not valid EBML

  let length = 1;
  for (let marker = 0x80; marker; marker >>= 1, length++) {
    if (first & marker) break;
  }
  if (length > 8 || offset + length > bytes.length) return null;

  let value = keepMarker ? first : first & ((1 << (8 - length)) - 1);
  let allOnes = (first & ((1 << (8 - length)) - 1)) === (1 << (8 - length)) - 1;

  for (let i = 1; i < length; i++) {
    value = value * 256 + bytes[offset + i];
    if (bytes[offset + i] !== 0xff) allOnes = false;
  }

  // Value bits all set = "unknown size". Only meaningful for sizes, and the
  // caller decides what to do with it; reported rather than silently huge.
  return { value, length, unknown: !keepMarker && allOnes };
}

/**
 * A sliding window over a byte source.
 *
 * Elements are walked by SIZE, so the viewer jumps over anything it does not need
 *, which is the whole reason a multi-gigabyte film is workable. The window is
 * re-read only when a requested range is not already inside it, and the walk only
 * ever moves forward, so one buffer is enough.
 *
 * @param {(offset: number, length: number) => Promise<Uint8Array>} read
 * @param {number} size Total bytes available.
 */
function createWindow(read, size) {
  let start = 0;
  let buffer = new Uint8Array(0);

  return {
    /**
     * @param {number} offset
     * @param {number} length
     * @returns {Promise<Uint8Array|null>} null when the range is too large to
     *   hold or runs past the end. Null means "skip this", never a throw: an
     *   unreadable region of a film should cost us that region, not the whole
     *   extraction.
     */
    async at(offset, length) {
      if (length > WINDOW_BYTES || offset + length > size) return null;
      if (offset < start || offset + length > start + buffer.length) {
        start = offset;
        buffer = await read(offset, Math.min(WINDOW_BYTES, size - offset));
      }
      const from = offset - start;
      if (from + length > buffer.length) return null;
      return buffer.subarray(from, from + length);
    },
    get size() {
      return size;
    },
  };
}

/**
 * Walk the child elements of a region, yielding `{id, offset, size, headerSize}`.
 *
 * Everything inside a Matroska document is one of these. The walk is driven
 * entirely by the declared sizes, which is why an element we have never heard of
 * costs nothing: the caller ignores it and the loop steps over it.
 *
 * @param {{at: Function}} window
 * @param {number} start Offset of the first child.
 * @param {number} end Offset one past the last byte to consider.
 * @returns {AsyncGenerator<{id: number, offset: number, size: number, headerSize: number}>}
 */
async function* children(window, start, end) {
  let cursor = start;

  while (cursor < end) {
    // 12 bytes covers the widest id (4) plus the widest size (8) we accept.
    const head = await window.at(cursor, 12);
    if (!head || head.length < 2) return;

    const id = readVint(head, 0, true);
    if (!id) return;
    const size = readVint(head, id.length, false);
    if (!size) return;

    const headerSize = id.length + size.length;
    const offset = cursor + headerSize;

    if (size.unknown) {
      // An unknown-size element continues until a sibling appears. The only one
      // in practice is the top-level `Segment`, which is handled by the caller
      // as "the rest of the file" rather than reached through this walk.
      return;
    }

    yield { id: id.value, offset, size: size.value, headerSize };

    // Step to the next sibling. A zero-length element would spin the loop
    // forever, so the cursor must always advance by at least the header.
    cursor = offset + size.value;
  }
}

/**
 * Read the whole of a small element, or null.
 *
 * @param {{at: Function}} window
 * @param {{offset: number, size: number}} element
 */
async function readElement(window, element) {
  return window.at(element.offset, element.size);
}

/** @param {Uint8Array} bytes */
function utf8(bytes) {
  return new TextDecoder('utf-8').decode(bytes);
}

/** @param {Uint8Array} bytes */
function uint(bytes) {
  let value = 0;
  for (const byte of bytes) value = value * 256 + byte;
  return value;
}

/**
 * The byte offset of the `Cues` index, found through the `SeekHead`, or null.
 *
 * ## Why this exists, and what it is worth
 *
 * In Matroska a subtitle track's blocks live inside the video's clusters, and there is no
 * list of where they are. So the only way to find a track's cues was to WALK THE FILE:
 * measured on a 25 GB film, one track cost 3278 reads of 8 MiB, 27.5 GB, because the
 * clusters have to be read to reach the blocks inside them.
 *
 * The format provides an index instead. `SeekHead` is a small element near the start that
 * names the byte offset of other top-level elements, `Cues` among them, and `Cues` maps
 * timestamps to cluster byte positions. So the offset of the index is found in TWO tiny
 * reads (a 12-byte header and the ~100-byte `SeekHead` body), no matter how large the file
 * is, and the index then turns "walk 27.5 GB" into "seek and read a few clusters".
 *
 * Measured on that same film: `SeekHead` at byte 52, pointing to `Cues` at byte
 * 25247121664. Reading the `SeekHead` is a fixed cost; finding the same information by
 * walking was the 27.5 GB.
 *
 * Returns null when there is no `SeekHead` or it does not name `Cues`, which is a real
 * case: a file written by a streaming muxer may have neither, and such a file keeps the
 * scan. Null is "no index", never an error.
 *
 * @param {{at: Function, size: number}} window
 * @returns {Promise<{offset: number, size: number}|null>}
 */
async function findCues(window, segmentStart) {
  // `SeekHead` precedes the clusters in every file a muxer writes, so a bounded walk from
  // the segment start reaches it after a handful of elements. The bound keeps a malformed
  // file from walking the whole thing looking for an element that is not there.
  let seen = 0;
  for await (const element of children(window, segmentStart, window.size)) {
    if (++seen > 16) break;
    if (element.id === ID.SeekHead) {
      const body = await readElement(window, element);
      if (!body) continue;
      const entries = parseSeekHead(body);
      const cues = entries.find((entry) => entry.id === ID.Cues);
      if (!cues) continue;
      // **`SeekPosition` is relative to the segment DATA start, not the file**, so the
      // segment start has to be added. Measured on a 25 GB film: the entry said
      // 25247121664 and the `Cues` element was really at 25247121716, exactly `segmentStart`
      // further in. Reading at the raw position landed 52 bytes early, into the tail of the
      // previous element, so the id there was not `Cues` at all and the index was declared
      // missing while sitting right beside the address we had.
      const cuesOffset = segmentStart + cues.position;
      // The seek entry gives the offset of the `Cues` element HEADER, so read its header
      // to learn its length. The body can be tens of megabytes on a long film, so only the
      // header is read here; the entries are read on demand by `cueClusterRange`.
      const head = await window.at(cuesOffset, 12);
      if (!head) continue;
      const cid = readVint(head, 0, true);
      if (!cid || cid.value !== ID.Cues) continue;
      const csize = readVint(head, cid.length, false);
      if (!csize || csize.unknown) continue;
      return { offset: cuesOffset, size: cid.length + csize.length + csize.value };
    }
    // `Cues` after `Tracks` means the walk has gone past where a `SeekHead` would be, and
    // a `Cluster` means the media has started, so there is none.
    if (element.id === ID.Cluster || element.id === ID.Cues) return null;
  }
  return null;
}

/**
 * Parse a `SeekHead` body into `{id, position}` entries.
 *
 * The structure is `Seek` elements, each holding a `SeekID` (the target's element id, in
 * its raw vint form) and a `SeekPosition` (the target's offset relative to the segment
 * data start, which is what `Cues` uses here).
 *
 * @param {Uint8Array} body
 * @returns {Array<{id: number, position: number}>}
 */
function parseSeekHead(body) {
  const ID_SEEK = 0x4dbb;
  const ID_SEEK_ID = 0x53ab;
  const ID_SEEK_POSITION = 0x53ac;
  const entries = [];
  let cursor = 0;

  while (cursor < body.length) {
    const id = readVint(body, cursor, true);
    if (!id) break;
    cursor += id.length;
    const size = readVint(body, cursor, false);
    if (!size) break;
    cursor += size.length;
    const end = cursor + size.value;
    if (end > body.length) break;

    if (id.value === ID_SEEK) {
      let inner = cursor;
      let target = null;
      let position = null;
      while (inner < end) {
        const innerId = readVint(body, inner, true);
        if (!innerId) break;
        inner += innerId.length;
        const innerSize = readVint(body, inner, false);
        if (!innerSize) break;
        inner += innerSize.length;
        if (inner + innerSize.value > end) break;
        if (innerId.value === ID_SEEK_ID) target = uint(body.subarray(inner, inner + innerSize.value));
        else if (innerId.value === ID_SEEK_POSITION) position = uint(body.subarray(inner, inner + innerSize.value));
        inner += innerSize.value;
      }
      if (target !== null && position !== null) entries.push({ id: target, position });
    }
    cursor = end;
  }
  return entries;
}

/**
 * The byte range the `Cues` index says holds the clusters for a window of time.
 *
 * ## What this is for
 *
 * With the index in hand, a viewer does not need the whole film's cues to show the line
 * being spoken. It needs the cues near the playhead, which live in the clusters for that
 * stretch of time, and the index says exactly which clusters those are. So the FIRST
 * read is bounded by the window rather than by the film, and the rest is filled in later.
 *
 * `Cues` is a list of `CuePoint`s, each with a `CueTime` (in timestamp ticks) and a
 * `CueTrackPositions` naming a `CueClusterPosition` (a byte offset from the segment data
 * start). Reading the cluster from that position to the next cue point's position covers
 * the window.
 *
 * @param {{at: Function, size: number}} window
 * @param {{offset: number, size: number}} cuesIndex
 * @param {number} segmentStart
 * @param {number} fromSeconds
 * @param {number} toSeconds
 * @param {number} timecodeScale
 * @returns {Promise<{start: number, end: number}|null>} A byte range, or null.
 */
async function cueClusterRange(window, cuesIndex, segmentStart, fromSeconds, toSeconds, timecodeScale) {
  // The index can be tens of megabytes on a long film, so it is read in bounded pieces
  // rather than whole. The cue points are ordered by time, so a linear scan can stop as
  // soon as it passes `toSeconds`.
  const toTicks = (seconds) => Math.round((seconds * 1e9) / timecodeScale);
  const wantedFrom = toTicks(Math.max(0, fromSeconds));
  const wantedTo = toTicks(Math.max(0, toSeconds));

  const body = await window.at(cuesIndex.offset, cuesIndex.size);
  if (!body) return null;
  // Skip the `Cues` element's own header to reach its children.
  const cid = readVint(body, 0, true);
  const csize = readVint(body, cid.length, false);
  let cursor = cid.length + csize.length;

  let firstPosition = null;
  let lastPosition = null;
  while (cursor < body.length) {
    const id = readVint(body, cursor, true);
    if (!id) break;
    cursor += id.length;
    const size = readVint(body, cursor, false);
    if (!size) break;
    cursor += size.length;
    const end = cursor + size.value;
    if (end > body.length) break;

    if (id.value === 0xbb) {
      // CuePoint
      let inner = cursor;
      let time = null;
      let position = null;
      while (inner < end) {
        const iid = readVint(body, inner, true);
        if (!iid) break;
        inner += iid.length;
        const isz = readVint(body, inner, false);
        if (!isz) break;
        inner += isz.length;
        if (inner + isz.value > end) break;
        if (iid.value === 0xb3) {
          time = uint(body.subarray(inner, inner + isz.value));
        } else if (iid.value === 0xb7) {
          // CueTrackPositions: find CueClusterPosition inside.
          let j = inner;
          const jEnd = inner + isz.value;
          while (j < jEnd) {
            const jid = readVint(body, j, true);
            if (!jid) break;
            j += jid.length;
            const jsz = readVint(body, j, false);
            if (!jsz) break;
            j += jsz.length;
            if (j + jsz.value > jEnd) break;
            if (jid.value === 0xf1) position = uint(body.subarray(j, j + jsz.value));
            j += jsz.value;
          }
        }
        inner += isz.value;
      }
      if (time !== null && position !== null) {
        if (time >= wantedFrom && firstPosition === null) firstPosition = position;
        if (time <= wantedTo) lastPosition = position;
        if (time > wantedTo && firstPosition !== null) break;
      }
    }
    cursor = end;
  }

  if (firstPosition === null || lastPosition === null) return null;
  // The end of the range is the START of the next cluster the index names, or the start of
  // the index itself when this is the last window, since clusters precede `Cues`.
  let endOffset = cuesIndex.offset;
  if (lastPosition > firstPosition) endOffset = segmentStart + lastPosition;
  return { start: segmentStart + firstPosition, end: endOffset };
}

/** @param {Uint8Array} bytes */
function int16(bytes) {
  if (bytes.length < 2) return 0;
  const raw = (bytes[0] << 8) | bytes[1];
  // Signed: block timestamps are relative and legitimately negative, which is how
  // a block that lands before its cluster's base time is written.
  return raw >= 0x8000 ? raw - 0x10000 : raw;
}

/**
 * Parse a `Tracks` element into subtitle track records.
 *
 * @param {{at: Function}} window
 * @param {{offset: number, size: number}} element
 * @returns {Promise<Array<{number: number, codec: string, language: string|null,
 *   name: string|null, kind: 'text'|'image'|'other'}>>}
 */
async function parseTracks(window, element) {
  const tracks = [];

  for await (const entry of children(window, element.offset, element.offset + element.size)) {
    if (entry.id !== ID.TrackEntry) continue;

    let number = 0;
    let type = 0;
    let codec = '';
    let language = null;
    let name = null;
    // Whether the track carried any language element at all, which is a different
    // question from what it said. See the note on `language` below.
    let languageSeen = false;

    for await (const field of children(window, entry.offset, entry.offset + entry.size)) {
      const bytes = await readElement(window, field);
      if (!bytes) continue;

      switch (field.id) {
        case ID.TrackNumber:
          number = uint(bytes);
          break;
        case ID.TrackType:
          type = uint(bytes);
          break;
        case ID.CodecID:
          codec = utf8(bytes).replace(/\0+$/, '');
          break;
        case ID.Language: {
          const value = utf8(bytes).replace(/\0+$/, '').trim();
          // Normalised here, at the source, rather than by every caller. Matroska
          // writes `zho` where the word lists say `zh`, and a track that reaches
          // the panel as `zho` is matched by no list and marks nothing, while
          // looking perfectly correct. See `normaliseLanguage`.
          //
          // `und` is Matroska's own "undetermined", and normalisation turns it
          // into null so callers have one thing to check rather than two.
          language = normaliseLanguage(value);
          languageSeen = true;
          break;
        }
        case ID.LanguageIETF: {
          // More specific than `Language` (`zh-Hans` rather than `zho`), so it
          // wins when both are present.
          const value = utf8(bytes).replace(/\0+$/, '').trim();
          const normalised = normaliseLanguage(value);
          if (normalised) language = normalised;
          languageSeen = true;
          break;
        }
        case ID.Name:
          name = utf8(bytes).replace(/\0+$/, '').trim() || null;
          break;
        default:
          break;
      }
    }

    if (type !== TRACK_TYPE_SUBTITLE) continue;

    // **An absent `Language` is English, and that is the specification rather than
    // a guess.** Matroska defines the element as defaulting to `eng`, which is why
    // the CELLAR suite's seven-language file has its English track unlabelled,
    // `ffprobe` reports that track with no language tag and every other one
    // labelled. The spec's own text is explicit that its value is case-insensitive
    // and that "an empty string or the value 'eng' should be used for the default
    // language", and the default is English.
    //
    // This corrects an earlier "never guess" rule that collapsed the two cases and
    // left the English track unmatched by any word list, which is the worst
    // outcome available, because the panel offers the track, the user chooses it,
    // and nothing is ever marked.
    //
    // `und` is still different and still reported as null: it is a file SAYING the
    // language is undetermined, which is knowledge rather than absence.
    const resolved = language ?? (languageSeen ? null : 'en');

    tracks.push({
      number,
      codec,
      language: resolved,
      name,
      // True when the language was supplied by the format default rather than read
      // from the file, so a caller can distinguish a certainty from an inference.
      languageDefaulted: !languageSeen,
      kind: TEXT_CODECS.has(codec) ? 'text' : IMAGE_CODECS.has(codec) ? 'image' : 'other',
    });
  }

  return tracks;
}

/**
 * Decode one block payload into cue text, for a given codec.
 *
 * The payload's shape depends on the codec, and two of them need real work:
 *
 *   - `S_TEXT/UTF8` is the subtitle text verbatim, the SRT file's body, already
 *     UTF-8, with the timing moved into the container.
 *   - `S_TEXT/ASS` is NOT an ASS file. The `[Script Info]` and style blocks live in
 *     the track's `CodecPrivate`, and each block holds only the event FIELDS:
 *     `ReadOrder,Layer,Style,Name,MarginL,MarginR,MarginV,Effect,Text`. So the text
 *     is everything after the eighth comma, and it may itself contain commas,
 *     which is why this splits a bounded number of times rather than taking an
 *     index from a full split.
 *
 * @param {string} codec
 * @param {Uint8Array} payload
 * @returns {string}
 */
function decodeBlockText(codec, payload) {
  const raw = utf8(payload);

  if (codec === 'S_TEXT/ASS' || codec === 'S_TEXT/SSA' || codec === 'S_SSA/ASS' || codec === 'S_ASS') {
    // Eight fields precede `Text`. Splitting into 9 and dropping the first 8 keeps
    // any commas that belong to the text itself.
    const parts = raw.split(',');
    const body = parts.length > 8 ? parts.slice(8).join(',') : raw;
    return stripTags(body);
  }

  // **Every text codec goes through the tag stripper, not only ASS.** A file that
  // has been through a format conversion carries the previous format's markup in
  // its text, and `<font size="20" color="#000000">` is what `ffmpeg` writes when
  // it converts ASS to a text subtitle format. It is common in the wild, and left
  // in it puts the tag itself in the transcript as if it were a word.
  return stripTags(raw);
}

/**
 * Remove ASS override blocks and HTML-style tags, keeping the words.
 *
 * Both, together, because either can appear in any text codec: the container says
 * what the track IS, but the text inside it is whatever produced it, and a
 * converted track carries the other format's markup.
 *
 * @param {string} text
 */
function stripTags(text) {
  return (
    text
      // An ASS drawing block is vector commands, not words. Dropped whole rather
      // than letting its coordinates through as text.
      .replace(/\{\\p\d+\}[\s\S]*?\{\\p0\}/g, '')
      // Every other ASS override block is pure styling: position, alignment,
      // karaoke timing, fades.
      .replace(/\{[^}]*\}/g, '')
      // `<font …>`, `</font>`, `<c.classname>`, `<v Speaker>` and WebVTT's bare
      // `<00:00:01.000>` cue timestamps.
      .replace(/<[^>]*>/g, '')
      .replace(/&amp;/g, '&')
      .replace(/&lt;/g, '<')
      .replace(/&gt;/g, '>')
      .replace(/&nbsp;/g, ' ')
      // ASS hard and soft line breaks.
      .replace(/\\N/g, '\n')
      .replace(/\\n/g, ' ')
      .replace(/\\h/g, ' ')
      .trim()
  );
}


/**
 * Parse cue text out of a `Block` or `SimpleBlock` payload.
 *
 * Both start the same way: a vint track number, a signed 16-bit timestamp
 * RELATIVE to the cluster's base time, then a flags byte. `SimpleBlock` carries no
 * duration, which is why the Matroska specification has subtitle tracks use
 * `BlockGroup` instead, so a `SimpleBlock` cue gets `duration: 0` and the panel
 * infers the end from the next cue, exactly as it does for an SRT file that omits
 * one.
 *
 * @param {Uint8Array} payload
 * @returns {{track: number, relative: number, text: Uint8Array}|null}
 */
function parseBlockHeader(payload) {
  const track = readVint(payload, 0, false);
  if (!track) return null;
  const after = track.length;
  if (payload.length < after + 3) return null;

  const relative = int16(payload.subarray(after, after + 2));
  // Byte `after + 2` is the flags: keyframe, invisible, lacing, discardable. Lacing
  // would mean several frames share one block, which subtitle tracks do not use,
  // detected so a laced block is skipped rather than misread as text.
  const flags = payload[after + 2];
  if (flags & 0x06) return null;

  return { track: track.value, relative, text: payload.subarray(after + 3) };
}

/**
 * The default `TimecodeScale`, in nanoseconds per tick.
 *
 * Matroska stores block timestamps as integer TICKS, and the scale says how long a
 * tick is. One millisecond (`1_000_000` ns) is the default and what almost every
 * file uses.
 */
const DEFAULT_TIMECODE_SCALE = 1_000_000;

/**
 * Read `TimecodeScale` from the `Info` element.
 *
 * **This was missing, and its absence is a silent corruption.** The code used to
 * divide block ticks by 1000 to get seconds, which is correct ONLY when the scale
 * is the default one millisecond. A file that sets it to `100_000`, which is the
 * entire point of the CELLAR conformance suite's `test2.mkv`, has every timestamp
 * come out **ten times too large**: a two-minute film's subtitles land at twenty
 * minutes, with no error and a complete-looking transcript.
 *
 * Found by reading the conformance file list rather than by a failing test, which
 * is the uncomfortable part: every fixture we generate uses the default, so nothing
 * here could have caught it.
 *
 * @param {{at: Function}} window
 * @param {number} segmentStart
 * @param {number} segmentEnd
 * @returns {Promise<number>} Nanoseconds per tick.
 */
async function readTimecodeScale(window, segmentStart, segmentEnd) {
  for await (const element of children(window, segmentStart, segmentEnd)) {
    // `Info` precedes `Tracks` and every cluster, so passing either means it is
    // not there and there is no reason to walk the media looking for it.
    if (element.id === ID.Tracks || element.id === ID.Cluster) break;
    if (element.id !== ID.Info) continue;

    for await (const field of children(window, element.offset, element.offset + element.size)) {
      if (field.id !== ID.TimecodeScale) continue;
      const bytes = await window.at(field.offset, field.size);
      if (!bytes) break;
      const value = uint(bytes);
      // A zero or absurd scale means a malformed file. The default is the safer
      // answer: a wrong scale produces plausible timestamps that are silently off,
      // which is worse than an assumed one.
      if (Number.isFinite(value) && value >= 1000 && value <= 1e10) return value;
    }
    break;
  }
  return DEFAULT_TIMECODE_SCALE;
}

/**
 * Read and decode one cluster, pushing any cues it holds into `cues`.
 *
 * Extracted from the main walk so a WINDOWED read can call it for a cluster the index
 * named, by byte offset, without walking to it. That distinction is the whole point: a
 * walk from the segment start touches every cluster header on the way, which measured
 * 8.21 GB of reads just to step 7000 elements, while jumping straight to an offset is one
 * small read.
 *
 * @param {{at: Function}} window
 * @param {number} offset
 * @param {number} span
 * @param {Map<number, string>} codecByTrack
 * @param {Set<number>|null} wanted
 * @param {Map<number, Array<{start: number, duration: number, text: string}>>} cues
 * @param {(ticks: number) => number} ticksToSeconds
 * @returns {Promise<'ok'|'truncated'>}
 */
async function decodeCluster(window, offset, span, codecByTrack, wanted, cues, ticksToSeconds) {
  const cluster = await window.at(offset, span);
  if (!cluster) return 'truncated';

  const clusterWindow = {
    at: async (at, length) => {
      const from = at - offset;
      if (from < 0 || from + length > cluster.length) return null;
      return cluster.subarray(from, from + length);
    },
  };

  let base = 0;
  for await (const child of children(clusterWindow, offset, offset + cluster.length)) {
    if (child.id === ID.Timestamp) {
      const bytes = await clusterWindow.at(child.offset, child.size);
      if (bytes) base = uint(bytes);
      continue;
    }

    const isSimple = child.id === ID.SimpleBlock;
    const isGroup = child.id === ID.BlockGroup;
    if (!isSimple && !isGroup) continue;

    for await (const inner of children(clusterWindow, child.offset, child.offset + child.size)) {
      if (inner.id !== ID.Block) continue;

      const payload = await clusterWindow.at(inner.offset, inner.size);
      if (!payload) continue;
      const block = parseBlockHeader(payload);
      if (!block) continue;

      const codec = codecByTrack.get(block.track);
      if (!codec) continue;
      if (wanted && !wanted.has(block.track)) continue;

      let duration = 0;
      if (isGroup) {
        for await (const field of children(clusterWindow, child.offset, child.offset + child.size)) {
          if (field.id !== ID.BlockDuration) continue;
          const bytes = await clusterWindow.at(field.offset, field.size);
          if (bytes) duration = ticksToSeconds(uint(bytes));
        }
      }

      const text = decodeBlockText(codec, block.text);
      if (!text) continue;

      const list = cues.get(block.track) ?? [];
      list.push({ start: ticksToSeconds(base + block.relative), duration, text });
      cues.set(block.track, list);
    }
  }
  return 'ok';
}

/**
 * Read every text subtitle track and its cues from a Matroska file.
 *
 * @param {object} options
 * @param {(offset: number, length: number) => Promise<Uint8Array>} options.read
 *   Supplies bytes on demand. The viewer page passes a `File.slice()` wrapper, so
 *   a multi-gigabyte film is never held in memory.
 * @param {number} options.size Total file size in bytes.
 * @param {number[]} [options.trackNumbers] Only extract these tracks. Omitted
 *   means every text track, which is what discovery wants.
 * @returns {Promise<{
 *   tracks: Array<{number: number, codec: string, language: string|null,
 *     name: string|null, kind: 'text'|'image'|'other'}>,
 *   cues: Map<number, Array<{start: number, duration: number, text: string}>>,
 *   truncated: boolean,
 *   timecodeScale: number,
 * }>}
 */
export async function readMatroska({ read, size, trackNumbers, window: timeWindow }) {
  const window = createWindow(read, size);
  /** @type {Array<{number: number, codec: string, language: string|null, name: string|null, kind: string}>} */
  let tracks = [];
  /** @type {Map<number, Array<{start: number, duration: number, text: string}>>} */
  const cues = new Map();
  // True when a cluster was too large to hold, or a region could not be read. The
  // caller reports it rather than presenting a partial transcript as complete.
  let truncated = false;

  // The document is `EBML` then `Segment`, and `Segment` is often written with an
  // UNKNOWN size, meaning "to the end of the file". So the walk is driven from
  // the file's own boundaries rather than from the segment's declared length.
  let segmentStart = 0;
  let segmentEnd = size;

  for await (const element of children(window, 0, size)) {
    if (element.id === ID.Segment) {
      segmentStart = element.offset;
      segmentEnd = element.size ? Math.min(size, element.offset + element.size) : size;
      break;
    }
  }

  // Ticks to seconds uses the file's OWN scale, not an assumed millisecond. A file
  // that sets it to 100,000 would otherwise have every timestamp ten times too
  // large, see `readTimecodeScale`.
  const timecodeScale = await readTimecodeScale(window, segmentStart, segmentEnd);
  const ticksToSeconds = (ticks) => (ticks * timecodeScale) / 1e9;

  // Falls back to a region we can actually read when a cluster's size is unknown,
  // which is how live-stream recordings are written.
  let lastGoodEnd = segmentStart;

  // **A time window narrows the walk, using the file's own index.** Without this the walk
  // below visits every cluster of the file, which on a 25 GB film is 27.5 GB of reads for
  // one subtitle track. With it, `Cues` names the cluster byte range holding the window, so
  // only those clusters are visited and the rest of the film is never read. A file with no
  // index (a streaming muxer may write none) returns null here and keeps the full walk,
  // which is slow but correct.
  let walkStart = segmentStart;
  let walkEnd = segmentEnd;
  if (timeWindow) {
    const index = await findCues(window, segmentStart);
    if (index) {
      const range = await cueClusterRange(
        window,
        index,
        segmentStart,
        timeWindow.from,
        timeWindow.to,
        timecodeScale,
      );
      if (range) {
        walkStart = Math.max(segmentStart, range.start);
        walkEnd = Math.min(segmentEnd, range.end);
      }
    }
  }

  // Pass one: find `Tracks`. It precedes the clusters in every file a muxer
  // writes, so one forward walk finds it and then continues into the clusters.
  /** @type {Map<number, string>} Track number -> codec, so block payloads can be
   *  decoded without re-reading the track list. */
  const codecByTrack = new Map();
  const wanted = trackNumbers ? new Set(trackNumbers) : null;

  for await (const element of children(window, segmentStart, segmentEnd)) {
    if (element.id === ID.Tracks) {
      if (!tracks.length) {
        tracks = await parseTracks(window, element);
        for (const track of tracks) {
          if (track.kind === 'text') codecByTrack.set(track.number, track.codec);
        }
      }
      // Discovery asks for NO tracks (`trackNumbers: []`), and `Tracks` always
      // precedes the clusters, so this is the point at which the answer is
      // complete. Stopping here is what keeps listing a film's subtitle tracks
      // cheap: without it the walk would read every cluster of a multi-gigabyte
      // file to decide it wanted none of them.
      if (wanted && wanted.size === 0) break;
      // **A windowed read stops here too.** `Tracks` is all this walk is for in that case:
      // the clusters it wants were already named by the index and are decoded by the jump
      // below. Continuing would step every cluster header of the file, which is the walk
      // the index exists to avoid.
      if (timeWindow && walkStart > segmentStart) break;
      continue;
    }

    if (element.id !== ID.Cluster) continue;

    // **Outside the requested window, so it is stepped over rather than read.** The walk
    // still starts at the segment so `Tracks` (which precedes the clusters) is found, but a
    // windowed read must not touch a cluster it was not asked for. This is what turns a
    // 27.5 GB scan into a read of the clusters the index named.
    if (element.offset + element.size <= walkStart || element.offset >= walkEnd) continue;

    // Nothing to extract from, so there is no reason to walk the media.
    if (!codecByTrack.size) continue;

    // **An unknown-size cluster is how live-stream recordings are written.** The
    // size is all-ones because the muxer could not know it in advance, so there is
    // no declared end to read to. Falling back to "from here to the end of the
    // known-good region" keeps such a file readable instead of yielding nothing,
    // `test4.mkv` in the CELLAR conformance suite exists for exactly this, and the
    // previous code skipped unknown sizes outright, so every cue in that file was
    // silently discarded.
    const declared = element.unknown ? null : element.size;
    if (declared !== null && declared > MAX_ELEMENT_BYTES) {
      truncated = true;
      continue;
    }
    const span = declared ?? segmentEnd - element.offset;

    // A cluster larger than one window cannot be held whole, so it is skipped, but
    // the read itself must stay inside the region we can vouch for, because a
    // window that reaches past the end returns nothing and would look identical to
    // an empty cluster.
    if (span > MAX_ELEMENT_BYTES) {
      truncated = true;
      continue;
    }

    const cluster = await decodeCluster(
      window,
      element.offset,
      span,
      codecByTrack,
      wanted,
      cues,
      ticksToSeconds,
    );
    if (cluster === 'truncated') {
      truncated = true;
      continue;
    }

    // A read that got this far consumed a readable region, so the fallback for an
    // unknown-size cluster can resume after it rather than restarting.
    lastGoodEnd = element.offset + span;
  }

  // **The windowed read: JUMP to the clusters the index named, do not walk to them.**
  // The loop above starts at the segment so it finds `Tracks`, and stepping from there is
  // what a full read must do. But a windowed read only wants a few clusters, and walking
  // to them costs every header in between (measured: 8.21 GB to step 7000 elements), which
  // would defeat the index. So when a window was requested and the index gave a byte range,
  // the clusters in that range are decoded directly by offset and nothing else is read.
  if (timeWindow && walkStart > segmentStart) {
    let offset = walkStart;
    while (offset < walkEnd) {
      const head = await window.at(offset, 12);
      if (!head || head.length < 2) break;
      const cid = readVint(head, 0, true);
      if (!cid || cid.value !== ID.Cluster) break;
      const csize = readVint(head, cid.length, false);
      if (!csize || csize.unknown) break;
      const bodyOffset = offset + cid.length + csize.length;
      if (csize.value > MAX_ELEMENT_BYTES) {
        truncated = true;
      } else if (
        (await decodeCluster(window, bodyOffset, csize.value, codecByTrack, wanted, cues, ticksToSeconds)) ===
        'ok'
      ) {
        // Decoded, so advance to the next cluster.
      }
      offset = bodyOffset + csize.value;
    }
  }

  // Reported so a caller can tell a wrong-scale file from a right one; the viewer
  // page does not use it, but a conformance test does.
  void lastGoodEnd;

  for (const list of cues.values()) list.sort((a, b) => a.start - b.start);

  // `timecodeScale` is returned so a conformance test can assert it was READ rather
  // than defaulted, a wrong value produces plausible timestamps, so only knowing
  // the value distinguishes "correct" from "silently ten times off".
  return { tracks, cues, truncated, timecodeScale };
}

/**
 * The languages available in a Matroska file, for track discovery.
 *
 * Separate from cue extraction because discovery only reads `Tracks`, which is at
 * the start of the file and cheap, so the panel can list a film's subtitle
 * tracks without the cost of walking its media.
 *
 * @param {object} options
 * @param {(offset: number, length: number) => Promise<Uint8Array>} options.read
 * @param {number} options.size
 */
export async function readMatroskaTracks({ read, size }) {
  const { tracks } = await readMatroska({ read, size, trackNumbers: [] });
  return tracks;
}

/** Whether a codec holds text we can mark. */
export function isTextCodec(codec) {
  return TEXT_CODECS.has(codec);
}

/**
 * A human name for an image subtitle codec, or null.
 *
 * Exists so the panel can name the reason rather than showing a track that
 * produces nothing, "Blu-ray PGS subtitles are images and cannot be read" is
 * actionable; an empty transcript is not.
 *
 * @param {string} codec
 */
export function imageCodecName(codec) {
  return IMAGE_CODECS.get(codec) ?? null;
}

