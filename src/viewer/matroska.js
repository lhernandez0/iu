/**
 * Normalise a language tag to what the rest of the extension expects.
 *
 * Handles all three shapes that reach here:
 *   `zho`     -> `zh`       (ISO 639-2, what Matroska writes)
 *   `zh-Hans` -> `zh-Hans`  (already specific; the script is meaningful and kept)
 *   `zh`      -> `zh`       (already correct)
 *
 * @param {string|null} code
 * @returns {string|null} null when unknown, so callers report rather than guess.
 */
export function normaliseLanguage(code) {
  if (!code) return null;
  const lower = String(code).trim().toLowerCase();
  if (!lower || lower === 'und') return null;

  // A regional or script variant: normalise the BASE and keep the rest, so
  // `zho-Hans` becomes `zh-Hans` rather than being rejected for a shape the
  // word lists could have handled.
  const [base, ...rest] = lower.split('-');
  const mapped = ISO639_2_TO_1.get(base) ?? base;
  if (rest.length) {
    // Region and script subtags are conventionally lower and title case
    // respectively, and the panel compares these as opaque strings.
    return [mapped, ...rest.map((part) => (part.length === 4 ? part.charAt(0).toUpperCase() + part.slice(1) : part))].join('-');
  }
  return mapped;
}

